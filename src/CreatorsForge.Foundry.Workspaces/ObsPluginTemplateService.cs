    private static string RenderOutput(
        FoundryObsPlugin plugin,
        FoundryObsDesign design,
        string symbol) => $$"""
        /* Generated by Creators Forge Foundry. Template: {{design.Template}} */
        #include <obs-module.h>

        #define {{CreateMacroIdentifier(symbol)}}_ID "{{EscapeCString(design.ComponentId)}}"

        static const char *{{symbol}}_name(void *unused)
        {
            UNUSED_PARAMETER(unused);
            return "{{EscapeCString(design.ComponentName)}}";
        }

        struct {{symbol}}_context {
            obs_output_t *output;
        };

        static void *{{symbol}}_create(obs_data_t *settings, obs_output_t *output)
        {
            UNUSED_PARAMETER(settings);
            struct {{symbol}}_context *context = bzalloc(sizeof(*context));
            context->output = output;
            return context;
        }

        static void {{symbol}}_destroy(void *data)
        {
            bfree(data);
        }

        static bool {{symbol}}_start(void *data)
        {
            struct {{symbol}}_context *context = data;
            if (!obs_output_can_begin_data_capture(context->output, 0) ||
                !obs_output_initialize_encoders(context->output, 0)) {
                return false;
            }

            obs_output_begin_data_capture(context->output, 0);
            return true;
        }

        static void {{symbol}}_stop(void *data, uint64_t timestamp)
        {
            struct {{symbol}}_context *context = data;
            obs_output_end_data_capture(context->output);
            UNUSED_PARAMETER(timestamp);
        }

        static void {{symbol}}_encoded_packet(void *data, struct encoder_packet *packet)
        {
            UNUSED_PARAMETER(data);
            UNUSED_PARAMETER(packet);
            /* Send or persist encoded packets here. */
        }

        static struct obs_output_info {{symbol}}_info = {
            .id = {{CreateMacroIdentifier(symbol)}}_ID,
            .flags = OBS_OUTPUT_AV | OBS_OUTPUT_ENCODED,
            .get_name = {{symbol}}_name,
            .create = {{symbol}}_create,
            .destroy = {{symbol}}_destroy,
            .start = {{symbol}}_start,
            .stop = {{symbol}}_stop,
            .encoded_packet = {{symbol}}_encoded_packet,
        };

        bool {{plugin.EntrySymbol}}(void)
        {
            obs_register_output(&{{symbol}}_info);
            blog(LOG_INFO, "[Creators Forge] Registered {{EscapeCString(design.ComponentName)}}.");
            return true;
        }
        """;

    private static string CreateCIdentifier(string value)
    {
        var builder = new StringBuilder("foundry_");
        foreach (var character in value)
        {
            builder.Append(char.IsAsciiLetterOrDigit(character) ? character : '_');
        }

        return builder.ToString();
    }

    private static string CreateMacroIdentifier(string value) =>
        value.ToUpperInvariant();

    private static string EscapeCString(string value) => value
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal)
        .Replace("\r", "\\r", StringComparison.Ordinal)
        .Replace("\n", "\\n", StringComparison.Ordinal);

    private static string NormalizeNewLines(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd() + "\n";
}
